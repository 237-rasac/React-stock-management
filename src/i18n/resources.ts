export const loadFeatureTranslations = async (namespace: string) => {
  const [fr, en] = await Promise.all([
    import(`@/features/${namespace}/translations/fr.json`),
    import(`@/features/${namespace}/translations/en.json`),
  ]);

  return {
    fr: { [namespace]: fr.default },
    en: { [namespace]: en.default },
  };
};